import { mkdir, writeFile, copyFile, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';
import { manifest } from '../src/manifest.mjs';
import { manifestTools } from '../src/tools.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pluginDir = join(root, 'cindy-plugin');
const iconSource = join(root, 'assets', 'icon.png');
const iconTarget = join(pluginDir, 'assets', 'icon.png');
const secretKey = manifest.network.secrets[0].key;

// cindy-plugin/ holds only shipped files. Everything a developer edits lives in
// src/; this script is what turns src/ into the package the host installs.
await mkdir(join(pluginDir, 'assets'), { recursive: true });

const ghost = {
  ...manifest,
  tools: manifestTools(),
};
await writeFile(join(pluginDir, 'ghost.json'), `${JSON.stringify(ghost, null, 2)}\n`);

if (existsSync(iconSource)) {
  await copyFile(iconSource, iconTarget);
} else if (!existsSync(iconTarget)) {
  throw new Error('assets/icon.png is missing');
}

await copyFile(join(root, 'src', 'settings.html'), join(pluginDir, 'settings.html'));

// The settings page cannot import the manifest, so the secret key is baked in
// at build time instead of being retyped in the UI source.
const settingsSource = await readFile(join(root, 'src', 'settings.js'), 'utf8');
await writeFile(
  join(pluginDir, 'settings.js'),
  settingsSource.replaceAll('__TICKTICK_SECRET_KEY__', secretKey),
);

await build({
  entryPoints: [join(root, 'src', 'cindy-entry.mjs')],
  outfile: join(pluginDir, 'main.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome110'],
  legalComments: 'none',
  banner: {
    js: '// Generated by `npm run build` from src/. Do not edit directly.',
  },
});

console.log(`Built ${join(pluginDir, 'ghost.json')}`);
console.log(`Built ${join(pluginDir, 'main.js')}`);
console.log(`Copied ${join(pluginDir, 'settings.html')}`);
console.log(`Built ${join(pluginDir, 'settings.js')}`);
